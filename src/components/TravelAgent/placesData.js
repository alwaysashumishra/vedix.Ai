/**
 * Filter places intelligently based on user search query, current transport mode, and category filter
 * Explicitly prioritizes:
 * - When mode is 'bus': Bus Stations & ISBTs with district name at the very top.
 * - When mode is 'train': Railway Stations and Junctions of that place at the very top.
 * - When mode is 'flight': Airport name of that place at the very top.
 *
 * @param {string} query Search input string
 * @param {string} mode Transport mode ("train" | "flight" | "bus" | "cab")
 * @param {string} filterType "all" | "district" | "subdistrict" | "transit" | "airport" | "station" | "bus"
 * @returns {Array} List of matching place items
 */
export function searchPlaces(query = "", mode = "", filterType = "all") {
  const cleanQ = query.toLowerCase().trim();
  const selectedMode = mode ? mode.toLowerCase() : "";

  let pool = PLACES_DATABASE;

  // Filter by category tab if selected
  if (filterType === "district") {
    pool = pool.filter((p) => p.type === "district" || p.type === "city");
  } else if (filterType === "subdistrict") {
    pool = pool.filter((p) => p.type === "subdistrict");
  } else if (filterType === "transit") {
    pool = pool.filter((p) => p.type === "station" || p.type === "airport" || p.type === "bus" || p.type === "cab");
  } else if (filterType === "station") {
    pool = pool.filter((p) => p.type === "station");
  } else if (filterType === "airport") {
    pool = pool.filter((p) => p.type === "airport");
  } else if (filterType === "bus") {
    pool = pool.filter((p) => p.type === "bus");
  }

  // Filter by transport mode if specified
  if (selectedMode) {
    pool = pool.filter((p) => {
      if (p.modes && p.modes.includes(selectedMode)) return true;
      if (p.type === "district" || p.type === "subdistrict" || p.type === "city") return true;
      return false;
    });
  }

  // If query is empty, return top recommendations tailored to the mode
  if (!cleanQ) {
    if (selectedMode === "bus") {
      const buses = pool.filter((p) => p.type === "bus" && p.popular);
      const districts = pool.filter((p) => p.type === "district" && p.popular);
      return [...buses, ...districts].slice(0, 12);
    } else if (selectedMode === "train") {
      const stations = pool.filter((p) => p.type === "station" && p.popular);
      const districts = pool.filter((p) => p.type === "district" && p.popular);
      return [...stations, ...districts].slice(0, 12);
    } else if (selectedMode === "flight") {
      const airports = pool.filter((p) => p.type === "airport" && p.popular);
      const districts = pool.filter((p) => p.type === "district" && p.popular);
      return [...airports, ...districts].slice(0, 12);
    }
    const popularList = pool.filter((p) => p.popular);
    return popularList.length > 0 ? popularList.slice(0, 12) : pool.slice(0, 12);
  }

  // Multi-field relevance scoring with mode-first boost
  const matches = [];

  for (const place of pool) {
    const nameLower = place.name.toLowerCase();
    const cityLower = (place.city || "").toLowerCase();
    const distLower = (place.district || "").toLowerCase();
    const subDistLower = (place.subDistrict || "").toLowerCase();
    const codeLower = (place.code || "").toLowerCase();
    const stateLower = (place.state || "").toLowerCase();
    const subTextLower = (place.subText || "").toLowerCase();

    let score = 0;

    // Exact matches
    if (codeLower === cleanQ) score += 150;
    else if (nameLower === cleanQ) score += 120;
    else if (distLower === cleanQ || cityLower === cleanQ) score += 95;
    else if (subDistLower === cleanQ) score += 85;

    // Prefix matches
    else if (nameLower.startsWith(cleanQ)) score += 75;
    else if (distLower.startsWith(cleanQ)) score += 65;
    else if (cityLower.startsWith(cleanQ)) score += 60;
    else if (codeLower.startsWith(cleanQ)) score += 55;

    // Word boundary matches
    else if (nameLower.includes(" " + cleanQ)) score += 45;
    else if (distLower.includes(" " + cleanQ)) score += 40;
    else if (subTextLower.includes(" " + cleanQ)) score += 35;

    // Substring matches
    else if (nameLower.includes(cleanQ)) score += 30;
    else if (distLower.includes(cleanQ)) score += 28;
    else if (cityLower.includes(cleanQ)) score += 25;
    else if (subTextLower.includes(cleanQ)) score += 20;
    else if (stateLower.includes(cleanQ)) score += 15;

    if (score === 0) continue;

    // =========================================================================
    // MODE-SPECIFIC PROMINENCE BOOST (Direct User Request)
    // - Bus mode: Bus Stations & ISBTs show top with district name
    // - Train mode: Railway Stations & Junctions of that place show top
    // - Flight mode: Airport of that place shows top
    // =========================================================================
    if (selectedMode === "bus") {
      if (place.type === "bus") {
        score += 80; // High priority boost for bus stands
        // Extra boost if user searched the district or city of this bus stand
        if (distLower.includes(cleanQ) || cityLower.includes(cleanQ) || nameLower.includes(cleanQ)) {
          score += 40;
        }
      }
    } else if (selectedMode === "train") {
      if (place.type === "station") {
        score += 80; // High priority boost for railway stations & junctions
        // Extra boost if user searched the district or city of this station
        if (distLower.includes(cleanQ) || cityLower.includes(cleanQ) || nameLower.includes(cleanQ)) {
          score += 40;
        }
      }
    } else if (selectedMode === "flight") {
      if (place.type === "airport") {
        score += 90; // High priority boost for airports
        // Extra boost if user searched the district or city of this airport
        if (distLower.includes(cleanQ) || cityLower.includes(cleanQ) || nameLower.includes(cleanQ)) {
          score += 50;
        }
      }
    } else if (selectedMode === "cab") {
      if (place.type === "cab" || (place.modes && place.modes.includes("cab"))) {
        score += 20;
      }
    }

    matches.push({ ...place, matchScore: score });
  }

  // Sort by highest match score descending
  matches.sort((a, b) => b.matchScore - a.matchScore);

  return matches.slice(0, 18);
}

/**
 * Helper to find a place by query or return a generic fallback
 */
export function findPlaceByQuery(query = "") {
  if (!query) return PLACES_DATABASE[0];
  const results = searchPlaces(query);
  return results.length > 0 ? results[0] : null;
}
